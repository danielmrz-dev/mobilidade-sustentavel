-- =====================================================================
-- V1 - Estrutura inicial do banco (Oracle)
-- Prefixo TB_MOB_ evita conflito com outras tabelas do mesmo schema
-- =====================================================================

CREATE TABLE TB_MOB_EMPRESA (
    ID                  NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME                VARCHAR2(120)  NOT NULL,
    CNPJ                VARCHAR2(14)   NOT NULL,
    META_CO2_MENSAL_KG  NUMBER(12,2),
    CRIADO_EM           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MOB_EMPRESA PRIMARY KEY (ID),
    CONSTRAINT UK_MOB_EMPRESA_CNPJ UNIQUE (CNPJ),
    CONSTRAINT CK_MOB_EMPRESA_META CHECK (META_CO2_MENSAL_KG IS NULL OR META_CO2_MENSAL_KG >= 0)
);

CREATE TABLE TB_MOB_USUARIO (
    ID            NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME          VARCHAR2(100)  NOT NULL,
    EMAIL         VARCHAR2(150)  NOT NULL,
    SENHA         VARCHAR2(100)  NOT NULL,
    PERFIL        VARCHAR2(20)   NOT NULL,
    SALDO_PONTOS  NUMBER(10)     DEFAULT 0 NOT NULL,
    EMPRESA_ID    NUMBER(19),
    CRIADO_EM     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MOB_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UK_MOB_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_MOB_USUARIO_PERFIL CHECK (PERFIL IN ('USER', 'ADMIN')),
    CONSTRAINT CK_MOB_USUARIO_SALDO CHECK (SALDO_PONTOS >= 0),
    CONSTRAINT FK_MOB_USUARIO_EMPRESA FOREIGN KEY (EMPRESA_ID) REFERENCES TB_MOB_EMPRESA (ID)
);

CREATE TABLE TB_MOB_MODAL (
    ID                  NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME                VARCHAR2(60)  NOT NULL,
    TIPO                VARCHAR2(30)  NOT NULL,
    FATOR_EMISSAO_G_KM  NUMBER(8,2)   NOT NULL,
    STATUS              VARCHAR2(10)  DEFAULT 'ATIVO' NOT NULL,
    CONSTRAINT PK_MOB_MODAL PRIMARY KEY (ID),
    CONSTRAINT UK_MOB_MODAL_NOME UNIQUE (NOME),
    CONSTRAINT CK_MOB_MODAL_TIPO CHECK (TIPO IN (
        'A_PE', 'BICICLETA', 'PATINETE_ELETRICO', 'ONIBUS', 'METRO_TREM',
        'CARRO_ELETRICO', 'CARONA', 'MOTO_COMBUSTAO', 'CARRO_COMBUSTAO')),
    CONSTRAINT CK_MOB_MODAL_FATOR CHECK (FATOR_EMISSAO_G_KM >= 0),
    CONSTRAINT CK_MOB_MODAL_STATUS CHECK (STATUS IN ('ATIVO', 'INATIVO'))
);

CREATE TABLE TB_MOB_DESLOCAMENTO (
    ID                 NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USUARIO_ID         NUMBER(19)     NOT NULL,
    MODAL_ID           NUMBER(19)     NOT NULL,
    DISTANCIA_KM       NUMBER(8,2)    NOT NULL,
    DATA_DESLOCAMENTO  DATE           NOT NULL,
    ORIGEM             VARCHAR2(120),
    DESTINO            VARCHAR2(120),
    CO2_EMITIDO_KG     NUMBER(12,3)   NOT NULL,
    CO2_EVITADO_KG     NUMBER(12,3)   NOT NULL,
    PONTOS_GERADOS     NUMBER(10)     NOT NULL,
    CRIADO_EM          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MOB_DESLOCAMENTO PRIMARY KEY (ID),
    CONSTRAINT CK_MOB_DESLOC_DISTANCIA CHECK (DISTANCIA_KM > 0),
    CONSTRAINT FK_MOB_DESLOC_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES TB_MOB_USUARIO (ID),
    CONSTRAINT FK_MOB_DESLOC_MODAL FOREIGN KEY (MODAL_ID) REFERENCES TB_MOB_MODAL (ID)
);

CREATE TABLE TB_MOB_RECOMPENSA (
    ID            NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
    TITULO        VARCHAR2(100)  NOT NULL,
    DESCRICAO     VARCHAR2(255),
    CUSTO_PONTOS  NUMBER(10)     NOT NULL,
    ESTOQUE       NUMBER(10)     NOT NULL,
    CONSTRAINT PK_MOB_RECOMPENSA PRIMARY KEY (ID),
    CONSTRAINT CK_MOB_RECOMP_CUSTO CHECK (CUSTO_PONTOS > 0),
    CONSTRAINT CK_MOB_RECOMP_ESTOQUE CHECK (ESTOQUE >= 0)
);

CREATE TABLE TB_MOB_RESGATE (
    ID             NUMBER(19)  GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USUARIO_ID     NUMBER(19)  NOT NULL,
    RECOMPENSA_ID  NUMBER(19)  NOT NULL,
    PONTOS_GASTOS  NUMBER(10)  NOT NULL,
    DATA_RESGATE   TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MOB_RESGATE PRIMARY KEY (ID),
    CONSTRAINT FK_MOB_RESGATE_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES TB_MOB_USUARIO (ID),
    CONSTRAINT FK_MOB_RESGATE_RECOMP FOREIGN KEY (RECOMPENSA_ID) REFERENCES TB_MOB_RECOMPENSA (ID)
);

-- Indices nas chaves estrangeiras e nos filtros mais usados
CREATE INDEX IX_MOB_USUARIO_EMPRESA   ON TB_MOB_USUARIO (EMPRESA_ID);
CREATE INDEX IX_MOB_DESLOC_USUARIO    ON TB_MOB_DESLOCAMENTO (USUARIO_ID, DATA_DESLOCAMENTO);
CREATE INDEX IX_MOB_DESLOC_MODAL      ON TB_MOB_DESLOCAMENTO (MODAL_ID);
CREATE INDEX IX_MOB_RESGATE_USUARIO   ON TB_MOB_RESGATE (USUARIO_ID);
CREATE INDEX IX_MOB_RESGATE_RECOMP    ON TB_MOB_RESGATE (RECOMPENSA_ID);
